#!/usr/bin/env node
// Regenerates docs/content-reference.md from the lesson, quiz-bank and
// Run-the-Show data that ships in script.js.
//
//   npm install            (once; installs jsdom)
//   node scripts/build_content_reference.mjs
//
// The app is loaded headlessly in jsdom and window.SwitchUpContent
// .getReferenceRows() is called, so the document can never drift from the
// strings students actually see. Run scripts/generate_kokoro_narration.py
// afterwards to refresh the narration MP3s for any changed reference IDs.

import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadApp } from './lib/headless-app.mjs';

const OUT = path.join(ROOT, 'docs', 'content-reference.md');

const escapeCell = (value) => String(value).replace(/\|/g, '\\|');

function table(rows, withType) {
  const head = withType ? '| Ref ID | Type | Text |\n| --- | --- | --- |' : '| Ref ID | Text |\n| --- | --- |';
  const body = rows.map((row) => (withType
    ? `| \`${row.refId}\` | ${row.type} | ${escapeCell(row.text)} |`
    : `| \`${row.refId}\` | ${escapeCell(row.text)} |`)).join('\n');
  return `${head}\n${body}`;
}

function groupBySection(rows) {
  const sections = [];
  const bySection = new Map();
  rows.forEach((row) => {
    if (!bySection.has(row.section)) {
      bySection.set(row.section, []);
      sections.push(row.section);
    }
    bySection.get(row.section).push(row);
  });
  return sections.map((section) => ({ section, rows: bySection.get(section) }));
}

const w = loadApp();
if (!w.SwitchUpContent || typeof w.SwitchUpContent.getReferenceRows !== 'function') {
  throw new Error('script.js did not expose window.SwitchUpContent.getReferenceRows');
}
const rows = w.SwitchUpContent.getReferenceRows();
const lessons = groupBySection(rows.filter((r) => r.group === 'lesson'));
const banks = groupBySection(rows.filter((r) => r.group === 'quiz'));
const rts = groupBySection(rows.filter((r) => r.group === 'rts'));
const ui = rows.filter((r) => r.group === 'ui');

const out = [];
out.push('# SwitchUp Studio Content Reference');
out.push('');
out.push('Use these IDs when requesting copy edits. Example: "Change `L2-l2-ready-cpu.instruction` to ..." or "Adjust `Q-B3-04.prompt`."');
out.push('');
out.push('This file is generated by `node scripts/build_content_reference.mjs` from the data in `script.js`. Edit the text in `script.js`, regenerate this file, then run `scripts/generate_kokoro_narration.py` to refresh the narration MP3s.');
out.push('');
out.push('Notes:');
out.push('- Lesson entries use the source lesson step ID from `script.js`.');
out.push('- Quiz bank levels draw 10 random questions from the listed bank. The switcher is reset before every bank question, with M1 and M2 empty.');
out.push('- Run the Show levels use fixed sequences and keep state between steps. They also start with M1 and M2 empty.');
out.push('- In lessons and quizzes the key type and chroma colour are never auto-selected; the prompt always states them and the student presses them.');
out.push('- Quiz prompts that mention M1 or M2 without an explicit media load get a runtime prefix as a safety net: "Load Host to M1." and/or "Load Guest to M2."');
out.push('- If a student skips a quiz prompt once, the runtime text adds: "skipped once. It will return at the end. Skip it again for no credit."');
out.push('');
out.push('## Lessons');
lessons.forEach(({ section, rows: sectionRows }) => {
  out.push('');
  out.push(`### ${section}`);
  out.push('');
  out.push(table(sectionRows, true));
});
out.push('');
out.push('## Quiz Banks');
banks.forEach(({ section, rows: sectionRows }) => {
  out.push('');
  out.push(`### ${section}`);
  out.push('');
  out.push(table(sectionRows, false));
});
out.push('');
out.push('## Run The Show');
rts.forEach(({ section, rows: sectionRows }) => {
  out.push('');
  out.push(`### ${section}`);
  out.push('');
  out.push(table(sectionRows, false));
});
out.push('');
out.push('## UI Prompts');
out.push('');
out.push(table(ui, false));
out.push('');
out.push('## Backend Direction');
out.push('');
out.push('A full backend would be useful once this text needs non-technical editing. The cleanest next step would be to move lessons and quiz banks from `script.js` into versioned JSON files first. After that, an admin backend can edit the JSON and the app can validate each item against its required check logic. This keeps instructional text editable without risking the simulator mechanics.');
out.push('');
out.push('For voice narration, see `docs/tts-backend-plan.md`. The recommended direction is backend-generated, cached Kokoro audio keyed to these same reference IDs.');
out.push('');

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`wrote ${path.relative(ROOT, OUT)}: ${rows.length} rows`);
